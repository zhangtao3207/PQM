`timescale 1ns / 1ps

/*
 * 模块: pqm_adc_pacer
 * 功能:
 *   AD7606 采样节拍发生器：输出平均频率严格等于 25.6 kHz 的 CONVST 启动脉冲。
 *
 *   背景：一帧 RFG 取 N=512 点 = 一个 50 Hz 周期，要求采样率就是 25.6 kHz。
 *   旧工程 PQM 的 AD7606 启动是「驱动一空闲就立刻再启动」＝自由跑（约百 kSPS 量级，
 *   取决于 AD7606 实际转换时间），与 N=512 不符，因此需要本模块做控速。
 *
 * 原理（为什么是「26 位 + 增量 34361」）：
 *   50 MHz / 25.6 kHz = 1953.125 拍。1953.125 不是整数，"整数装载值 + 定长计数"
 *   给不出这个周期；而 1953.125 的二进制表示也没有有限位宽（小数部分 0.001 是无限循环），
 *   所以任何"整数装载值 + 定长计数"都不可能给出它。要平均严格，只能把周期当分数、
 *   用累加器做小数分频：每个时钟加 INC，溢出（进位）即为一次脉冲。
 *
 *       目标周期 = 1953.125 拍 = 15625 / 8 拍
 *       频率字   INC = 2^26 / 1953.125 = 34359.738  →  取 34361
 *
 *   为什么 2^26 / INC 不能精确等于 1953.125：1953.125 = 15625/8，而 15625 = 5^6
 *   与 2 互素，任何 2 的幂作模数都约不掉因子 5^6。所以单个周期的比值必然带小数。
 *   能做到"平均严格"的判据是**整数拍窗口内脉冲数恰好为整数**：
 *       15625 拍 x 34361 / 2^26 = 8000.026  →  进位 8000 次
 *       平均间隔 = 15625 / 8000 = 1953.125 拍 → 50 MHz / 1953.125 = 25600 Hz
 *   "8000.026 取整成 8000" 带来的频率偏差是 0.026 / 8000 = 3 ppm（约 0.08 Hz），
 *   根因是 15625 = 5^6 与 2 互素，任何 2 的幂作模数都约不掉因子 5^6，
 *   因此增量只能取整、平均频率必然带这一点点量化误差。
 *   同窗口内 INC = 34360（更接近 34359.738）也能得到 8000 次，
 *   但它的相邻间隔退化成恒定 1953 拍（2^25 x 34360 是 2^26 的整数倍），
 *   每 8 个脉冲漂移 -1 拍；34361 给出标准的 1953/1954 交替，故选它。
 *   TB 的 A 项用判据 |S x INC - n x 2^W| <= INC 直接验证这一点，不依赖推导。
 *
 *   （历史遗留：交接文件写的 INC = 1953125 是把"周期 1953.125"误当了"增量"，
 *     量纲不对：1953125 = 1953.125 x 1024，是把周期乘了 1024。那个值在 26 位下得到
 *     即 1.455 MHz，与 25.6 kHz 差 57 倍。已按本条推导修正。）
 *
 *   相邻脉冲间隔取 ⌊周期⌋ 或 ⌈周期⌉ = 1953 或 1954 拍，Bresenham 分布，
 *   长时无累积误差（每来一次进位，多余的和被模运算自然扣掉）。
 *
 *   抖动上限 = ±1 拍（±20 ns @50 MHz）；纯时基，不理会下游忙闲，
 *   重触发策略由调用方（将来的 PL 顶层）决定。
 *
 * 输入:
 *   clk: 系统时钟（50 MHz，与 AD7606 通路同域）。
 *   rst_n: 低有效同步复位；复位期间累加器清零，o_tick 保持为 0。
 *
 * 输出:
 *   o_tick: 1 拍宽的启动脉冲（约每 1953 拍一个），直接接 AD7606_Parallel_DRIVER 的 start。
 *
 * 参数:
 *   C_ACC_WIDTH: 累加器位宽（对应模数 2^C_ACC_WIDTH），默认 26。
 *   C_INC:       每个时钟的增量，默认 34361（= 2^26 / 1953.125 四舍五入）。
 *   两者按「平均间隔 = 2^C_ACC_WIDTH / C_INC」配对；改时钟或改采样率时一起改，
 *   TB 的 A 项判据会把配错的情况直接判死。
 */
module pqm_adc_pacer #(
    parameter integer C_ACC_WIDTH = 26,
    parameter integer C_INC       = 34361
) (
    input  wire clk,
    input  wire rst_n,
    output wire o_tick
);

// 累加器：位宽 = C_ACC_WIDTH，进位到第 C_ACC_WIDTH 位即溢出（等价取模 2^C_ACC_WIDTH）。
reg [C_ACC_WIDTH-1:0] acc;
wire [C_ACC_WIDTH:0]  acc_sum;

assign acc_sum = {1'b0, acc} + C_INC[0+:C_ACC_WIDTH+1];

// 溢出即脉冲。直接取组合进位，不额外打拍——累加器本身已是一级寄存器，
// 因此 o_tick 与 acc 的更新同拍，脉冲时刻就是累加器回绕的那一拍。
assign o_tick = acc_sum[C_ACC_WIDTH];

always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        acc <= {C_ACC_WIDTH{1'b0}};
    end else begin
        // 溢出时高位被丢弃＝自动扣掉模数，余数继续累积（这条性质保证平均无累积误差）。
        acc <= acc_sum[C_ACC_WIDTH-1:0];
    end
end

endmodule
